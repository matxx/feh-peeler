#!/usr/bin/env ruby

require 'plist'
require 'json'

names = []

Dir['assets/sprite-sheets/*.plist'].sort.map do |input_file|
  name = File.basename(input_file, '.plist')
  json_file = input_file.gsub(/\.plist\Z/, '.json')
  begin
    data = Plist.parse_xml(input_file)

    unless data
      puts 'Failed to parse plist file.'
    end

    # Extract only the frame data for a leaner JSON
    frames = data['frames'].map do |frame_name, config|
      # Convert "{x,y}" and "{{x,y},{w,h}}" strings into numeric arrays
      # textureRect format: {{x,y},{w,h}}
      rect = config['textureRect'].scan(/\d+/).map(&:to_i)
      # sprites are trimmed: spriteSourceSize is the untrimmed size and
      # spriteOffset the offset of the trimmed sprite center from the untrimmed one (y axis pointing up)
      source_size = config['spriteSourceSize'].scan(/-?\d+/).map(&:to_i)
      offset = config['spriteOffset'].scan(/-?\d+/).map(&:to_i)

      {
        name: frame_name,
        x: rect[0],
        y: rect[1],
        width: rect[2],
        height: rect[3],
        rotated: config['textureRotated'],
        sourceWidth: source_size[0],
        sourceHeight: source_size[1],
        trimLeft: ((source_size[0] - rect[2]) / 2.0 + offset[0]).round,
        trimTop: ((source_size[1] - rect[3]) / 2.0 - offset[1]).round
      }
    end

    size = data['metadata']['size'].scan(/\d+/).map(&:to_i)

    File.write(json_file, JSON.pretty_generate({
      width: size[0],
      height: size[1],
      frames: frames
    }))
    names << name

    puts "Successfully converted #{input_file} → #{json_file}"
  rescue StandardError => e
    puts "Error: #{e.message}"
    next
  end
end

File.write('assets/sprite-sheets/index.ts', <<~TS)
  // generated by bin/handle_sprite_sheets.sh
  #{names.map { |name| "import #{name} from './#{name}.json'\nimport #{name}Img from './#{name}.png'" }.join("\n")}

  export const SPRITE_SHEETS = {
  #{names.map { |name| "  #{name}: { ...#{name}, img: #{name}Img }," }.join("\n")}
  }
TS

puts 'Successfully created assets/sprite-sheets/index.ts'
